#!/usr/bin/env python3
"""Independent exact local coordinate-metric oracle, not a sampling proof.

The spatial jets are generated by a genuine metric family in stereographic
coordinates on S^3. Curvature is expanded directly from coordinate Christoffel
symbols in epsilon. No production geometry or angular code is imported here.
"""
from fractions import Fraction as F
from itertools import product
import argparse, hashlib, json
from pathlib import Path

N=5
I=range(N)
PAIRS=list(product(I,repeat=2))
TRIPLES=list(product(I,repeat=3))

class Jet:
    """Value, ordinary gradient, ordinary symmetric Hessian at one point."""
    def __init__(self,v=0,d=None,h=None):
        self.v=F(v);self.d=tuple(map(F,d or [0]*N))
        self.h=tuple(tuple(map(F,row)) for row in (h or [[0]*N for _ in I]))
    def __add__(self,b):
        b=asjet(b)
        return Jet(self.v+b.v,[self.d[i]+b.d[i] for i in I],[[self.h[i][j]+b.h[i][j] for j in I] for i in I])
    __radd__=__add__
    def __neg__(self):return self*(-1)
    def __sub__(self,b):return self+-asjet(b)
    def __rsub__(self,b):return asjet(b)+-self
    def __mul__(self,b):
        b=asjet(b)
        return Jet(self.v*b.v,[self.d[i]*b.v+self.v*b.d[i] for i in I],[[self.h[i][j]*b.v+self.d[i]*b.d[j]+self.d[j]*b.d[i]+self.v*b.h[i][j] for j in I] for i in I])
    __rmul__=__mul__
    def inv(self):
        v=1/self.v
        return Jet(v,[-v*v*x for x in self.d],[[2*v**3*self.d[i]*self.d[j]-v*v*self.h[i][j] for j in I] for i in I])
    def __truediv__(self,b):return self*asjet(b).inv()
    def __rtruediv__(self,b):return asjet(b)*self.inv()
    def __pow__(self,n):
        if n<0:return self.inv()**(-n)
        out=Jet(1)
        for _ in range(n):out=out*self
        return out
    def partial(self,i):return Jet(self.d[i],self.h[i])

def asjet(a):return a if isinstance(a,Jet) else Jet(a)
def coord(i,v=0):
    d=[0]*N;d[i]=1
    return Jet(v,d)
def matmul(a,b):return [[sum((a[i][k]*b[k][j] for k in I),Jet()) for j in I] for i in I]
def negmat(a):return [[-v for v in row] for row in a]
def seriesmul(a,b):return [sum((a[k]*b[n-k] for k in range(n+1)),Jet()) for n in range(3)]
def sadd(*xs):return [sum((x[k] for x in xs),Jet()) for k in range(3)]
def sscale(c,x):return [c*v for v in x]
def sdiff(x,d):return [v.partial(d) for v in x]

def manufactured(case=0):
    y,t=coord(0),coord(1)
    point=[F(1,2),F(1,3),F(1,4)] if case==0 else [F(1,3),F(-1,2),F(1,5)]
    x=[coord(i+2,v) for i,v in enumerate(point)]
    rho=2+F(3,7)*y+F(5,22)*y*y
    c=F(5,4)+F(3,4)*t+F(5,8)*t*t
    den=1+sum((z*z for z in x),Jet())
    kap=4/den**2
    f=x[0]*x[0]-x[1]*x[1]
    df=[2*x[0],-2*x[1],Jet()]
    Y=4*f/den**2
    DY=[4*(df[i]/den**2-4*f*x[i]/den**3) for i in range(3)]
    loggrad=[-2*z/den for z in x]
    HY={}
    for i,j in product(range(3),repeat=2):
        f2=2*([1,-1,0][i]) if i==j else 0
        partial2=4*(f2/den**2-4*(df[i]*x[j]+df[j]*x[i]+(f if i==j else 0))/den**3+24*f*x[i]*x[j]/den**4)
        HY[i,j]=partial2-loggrad[i]*DY[j]-loggrad[j]*DY[i]+(sum((loggrad[k]*DY[k] for k in range(3)),Jet()) if i==j else 0)
    names='ABCDELM'
    m={};amps={}
    for a,name in enumerate(names):
        vals=[F((-1)**(a+k+case)*(1+((a+2)*(k+3)+case)%11),17+k) for k in range(6)]
        for suffix,v in zip(('','y','t','yy','yt','tt'),vals):m[name+suffix]=v
        amps[name]=vals[0]+vals[1]*y+vals[2]*t+vals[3]*y*y/2+vals[4]*y*t+vals[5]*t*t/2
    sv=[F(2,3),F(-3,5),F(7,11),F(5,13),F(-2,7),F(11,17)]
    s=dict(zip(('s','sy','st','syy','syt','stt'),sv))
    etaamp=sv[0]+sv[1]*y+sv[2]*t+sv[3]*y*y/2+sv[4]*y*t+sv[5]*t*t/2
    eta=etaamp*Y
    phi=F(7,9)*y+F(-5,22)*y*y
    g=[[Jet() for _ in I] for _ in I]
    q=[[Jet() for _ in I] for _ in I]
    g[0][0]=Jet(1);g[1][1]=-rho*rho
    q[0][0]=amps['A']*Y;q[0][1]=q[1][0]=rho*amps['B']*Y
    q[1][1]=rho*rho*amps['D']*Y
    for i in range(3):
        g[i+2][i+2]=rho*rho*c*c*kap
        q[0][i+2]=q[i+2][0]=rho*c*amps['C']*DY[i]
        q[1][i+2]=q[i+2][1]=rho*rho*c*amps['E']*DY[i]
        for j in range(3):q[i+2][j+2]=rho*rho*c*c*((amps['L']*Y*kap if i==j else 0)+amps['M']*HY[i,j])
    b={'rho':F(2),'c':F(5,4),'theta':F(3,5),'a':F(3,14),'ay':F(5,22)-F(9,196),
       'p':F(7,9),'py':F(-5,11),'Vp':F(13,7),'Vpp':F(-11,5),'Vppp':F(17,3),'ell':F(1,1000000)}
    return g,q,phi,eta,m,s,b,point

def direct(g,q,phi,eta,b):
    gi=[[g[i][i].inv() if i==j else Jet() for j in I] for i in I]
    gi1=negmat(matmul(matmul(gi,q),gi));gi2=negmat(matmul(matmul(gi1,q),gi))
    inv={(i,j):[gi[i][j],gi1[i][j],gi2[i][j]] for i,j in PAIRS}
    metric={(i,j):[g[i][j],q[i][j],Jet()] for i,j in PAIRS}
    Gamma={}
    for a,c,d in TRIPLES:
        Gamma[a,c,d]=sscale(F(1,2),sadd(*(seriesmul(inv[a,e],sadd(sdiff(metric[e,d],c),sdiff(metric[e,c],d),sscale(-1,sdiff(metric[c,d],e)))) for e in I)))
    Ric={}
    for a,bidx in PAIRS:
        Ric[a,bidx]=sadd(*(sadd(sdiff(Gamma[c,a,bidx],c),sscale(-1,sdiff(Gamma[c,a,c],bidx))) for c in I),
                         *(sscale(sign,seriesmul(Gamma[c,c,d],Gamma[d,a,bidx])) if sign==1 else sscale(-1,seriesmul(Gamma[c,bidx,d],Gamma[d,a,c])) for c,d in PAIRS for sign in (1,-1)))
    C={a:sadd(*(seriesmul(inv[c,d],[Jet(),Gamma[a,c,d][1],Gamma[a,c,d][2]]) for c,d in PAIRS)) for a in I}
    Clow={a:sadd(*(seriesmul(metric[a,c],C[c]) for c in I)) for a in I}
    Cder={(a,c):sadd(sdiff(Clow[c],a),*(sscale(-1,seriesmul(Gamma[d,a,c],Clow[d])) for d in I)) for a,c in PAIRS}
    V=[Jet(F(19,13)),b['Vp']*eta,b['Vpp']*eta*eta/2]
    E={};Red={}
    for a,c in PAIRS:
        E[a,c]=sadd(Ric[a,c],sscale(-1,seriesmul([phi.partial(a),eta.partial(a),Jet()],[phi.partial(c),eta.partial(c),Jet()])),sscale(F(-2,3),seriesmul(V,metric[a,c])))
        Red[a,c]=sadd(E[a,c],sscale(F(-1,2),sadd(Cder[a,c],Cder[c,a])))
    scalar_hess={}
    for a,c in PAIRS:
        scalar_hess[a,c]=sadd([phi.partial(a).partial(c),eta.partial(a).partial(c),Jet()],*(sscale(-1,seriesmul(Gamma[d,a,c],[phi.partial(d),eta.partial(d),Jet()])) for d in I))
    scalar=sadd(*(seriesmul(inv[a,c],scalar_hess[a,c]) for a,c in PAIRS),[Jet(-b['Vp']),-b['Vpp']*eta,-b['Vppp']*eta*eta/2])
    value=lambda obj:{k:2*v[2].v for k,v in obj.items()}
    return {'QRic':value(Ric),'QE':value(E),'QEred_general':value(Red),'QC_lower_actual':value(Clow),'QC_upper':value(C),'Qphi_general':2*scalar[2].v},Gamma,gi

def indexed(g,q,phi,eta,b,Gamma,gi,mutation=None):
    g0=[[z.v for z in row] for row in g];h=[[z.v for z in row] for row in q]
    inv=[[z.v for z in row] for row in gi];gam={k:v[0] for k,v in Gamma.items()}
    dq={(a,c,d):q[c][d].partial(a)-sum((gam[e,a,c]*q[e][d]+gam[e,a,d]*q[c][e] for e in I),Jet()) for a,c,d in TRIPLES}
    ddq={}
    for a,c,d,e in product(I,repeat=4):
        ddq[a,c,d,e]=dq[c,d,e].d[a]-sum((gam[f,a,d].v*dq[c,f,e].v+gam[f,a,e].v*dq[c,d,f].v for f in I),F())
        if mutation!='derivative_slot':ddq[a,c,d,e]-=sum((gam[f,a,c].v*dq[f,d,e].v for f in I),F())
    iv=[inv[i][i] for i in I]
    if mutation=='time_raise':iv[1]=-iv[1]
    P={(a,c,d):iv[a]*(dq[c,d,a].v+dq[d,c,a].v-dq[a,c,d].v)/2 for a,c,d in TRIPLES}
    DP={(e,a,c,d):iv[a]*(ddq[e,c,d,a]+ddq[e,d,c,a]-ddq[e,a,c,d])/2 for e,a,c,d in product(I,repeat=4)}
    hu={(a,c):iv[a]*h[a][c] for a,c in PAIRS}
    hi={(a,c):iv[a]*iv[c]*h[a][c] for a,c in PAIRS}
    DJ={(e,a,c,d):-2*sum((iv[a]*dq[e,a,f].v*P[f,c,d]+hu[a,f]*DP[e,f,c,d] for f in I),F()) for e,a,c,d in product(I,repeat=4)}
    C1={a:sum((iv[c]*P[a,c,c] for c in I),F()) for a in I}
    QR={(a,c):sum((DJ[d,d,a,c]-DJ[c,d,a,d] for d in I),F())+2*sum((P[d,d,e]*P[e,a,c]-P[d,c,e]*P[e,a,d] for d,e in PAIRS),F()) for a,c in PAIRS}
    QE={(a,c):QR[a,c]-2*eta.d[a]*eta.d[c]-F(2,3)*(b['Vpp']*eta.v**2*g0[a][c]+2*b['Vp']*eta.v*h[a][c]) for a,c in PAIRS}
    QL={a:-2*sum((hi[c,d]*g0[a][a]*P[a,c,d] for c,d in PAIRS),F()) for a in I}
    QU={a:iv[a]*QL[a]-2*sum((hu[a,c]*C1[c] for c in I),F()) for a in I}
    DQL={(e,a):-2*g0[a][a]*sum((iv[c]*iv[d]*dq[e,c,d].v*P[a,c,d]+hi[c,d]*DP[e,a,c,d] for c,d in PAIRS),F()) for e,a in PAIRS}
    ER={(a,c):QE[a,c]-(DQL[a,c]+DQL[c,a])/2+2*sum((P[d,a,c]*g0[d][d]*C1[d] for d in I),F()) for a,c in PAIRS}
    Hphi={(a,c):phi.h[a][c]-sum((gam[d,a,c].v*phi.d[d] for d in I),F()) for a,c in PAIRS}
    Heta={(a,c):eta.h[a][c]-sum((gam[d,a,c].v*eta.d[d] for d in I),F()) for a,c in PAIRS}
    hhi={(a,c):sum((hu[a,d]*hi[d,c] for d in I),F()) for a,c in PAIRS}
    QS=2*sum((hhi[a,c]*Hphi[a,c]-hi[a,c]*Heta[a,c] for a,c in PAIRS),F())+2*sum((hi[a,c]*P[d,a,c]*phi.d[d] for a,c,d in TRIPLES),F())-b['Vppp']*eta.v**2
    QS+=2*sum((hu[a,c]*C1[c]*phi.d[a] for a,c in PAIRS),F())-2*sum((C1[a]*eta.d[a] for a in I),F())
    result={'QRic':QR,'QE':QE,'QEred_general':ER,'QC_lower_actual':QL,'QC_upper':QU,'Qphi_general':QS}
    aux={'dq':dq,'ddq':ddq,'P':P,'DP':DP,'C1':C1,'DQC_lower_actual':DQL}
    return result,aux

def compare(a,b,label):
    for key in a:
        if isinstance(a[key],dict):
            for j in a[key]:
                if a[key][j]!=b[key][j]:raise ValueError(f'{label}: {key} {j}')
        elif a[key]!=b[key]:raise ValueError(f'{label}: {key}')

def run(case=0):
    g,q,phi,eta,m,s,b,point=manufactured(case)
    reference,Gamma,gi=direct(g,q,phi,eta,b)
    result,aux=indexed(g,q,phi,eta,b,Gamma,gi)
    compare(reference,result,'INDEPENDENT_COORDINATE_VS_COVARIANT')
    controls=[]
    for mutation in ('derivative_slot','time_raise'):
        mutated,_=indexed(g,q,phi,eta,b,Gamma,gi,mutation)
        try:compare(reference,mutated,'INJECTED_'+mutation)
        except ValueError:controls.append(mutation)
        else:raise ValueError('MUTATION_NOT_DETECTED_'+mutation)
    if not any(aux['C1'].values()):raise ValueError('GENERAL_WITNESS_ACCIDENTALLY_HARMONIC')
    delta={k:sum((2*aux['P'][d,*k]*g[d][d].v*aux['C1'][d] for d in I),F()) for k in PAIRS}
    if not any(delta.values()):raise ValueError('HARMONIC_REDUCTION_MISUSE_NOT_DETECTED')
    controls.append('drop_general_2PC1_reduction_term')
    if all(result['QC_upper'][a]==gi[a][a].v*result['QC_lower_actual'][a] for a in I):raise ValueError('LOWERING_CONVENTION_CONTROL_NOT_DETECTED')
    controls.append('confuse_upper_QC_with_actual_lowered_Hessian')
    return {'case':case,'stereographic_point':list(map(str,point)),'exact_coordinate_comparison':'PASS','negative_controls':controls,
            'scope':'Genuine curved nonnormal metric/scalar family with all seven frame amplitudes and all ordinary y,t two-jets populated; finite witness only.'}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
    if args.output.exists():raise ValueError('OUTPUT_ALREADY_EXISTS')
    rows=[run(k) for k in range(2)]
    result={'status':'PASS_INDEPENDENT_COORDINATE_AFFINE_HESSIANS','checker_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'cases':rows,
        'convention':'Second epsilon derivatives; fixed reference connection; E=Ric-dphi*dphi-(2/3)Vg; Ered=E-nabla^g_(a C_b).',
        'not_a_universal_proof':'The companion derivation proves the universal identities; exact finite jets test implementation and conventions.'}
    args.output.write_text(json.dumps(result,indent=2)+'\n');print(result['status'])

if __name__=='__main__':main()
