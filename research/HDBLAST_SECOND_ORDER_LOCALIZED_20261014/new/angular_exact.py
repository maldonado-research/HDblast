"""Independent angular reduction for the Hamiltonian correction.

Run reproduce.py first: it always regenerates the source pickle from text
code before this verifier reads it. This standalone step expects that freshly
generated local source.
No original-engine module is imported. For a tangential trace-free h on a
radially conformally flat background, DH[h,0]=(2 Omega^4)^-1 partial_i
partial_j h_ij. The angular scalar Hessian construction gives the latter
as (s/(3 Omega^4)) Delta_S(Delta_S+3) chi. Spatial polynomials are reduced
modulo |x|^2=s before radial coefficients are substituted.

Radial coefficient derivatives vanish identically: for f(s) H_ij with
H_ij x_j=0 and tr H=0, the extra terms in partial_i partial_j(f H_ij)
are 2 f_i partial_j H_ij + f_ij H_ij. Differentiating x_i H_ij=0
gives x_i partial_j H_ij=-tr H=0; f_i is radial and f_ij is a combination
of delta_ij and x_i x_j. Both extra terms are therefore zero.

The companion note manuscript/ANGULAR_EXACT_VERIFICATION.md derives the
conformal and angular identities. The source itself is regenerated by the
original engine; this verifies its correction identity and does not claim
an independent symbolic derivation of the source Hessian.
"""
import hashlib
import json
from pathlib import Path
import pickle
import sys
import time
import sympy as sp

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
t0 = time.monotonic()
x = sp.symbols('x1:5')
s = sp.Symbol('s_')
O0 = sp.Symbol('O0')
r2 = sum(z*z for z in x)
xv = sp.Matrix(x)
P = r2*sp.eye(4)-xv*xv.T
def euler(f):
    return sum(x[i]*sp.diff(f,x[i]) for i in range(4))
def lap_sphere(f):
    return r2*sum(sp.diff(f,z,2) for z in x)-euler(euler(f))-2*euler(f)
def sphere_reduce(polynomial):
    polynomial = sp.Poly(sp.expand(polynomial), x[3])
    relation = s-sum(z*z for z in x[:3])
    return sp.expand(sum(coefficient*relation**(power//2)*x[3]**(power%2)
                         for (power,),coefficient in polynomial.terms()))

chi_basis = [x[0]**2+x[1]**2, (x[0]**2-x[1]**2)**2]
checks = []
angular_basis = []
for chi in chi_basis:
    PHP=P*sp.hessian(chi,x)*P
    h=r2*PHP-PHP.trace()*P/3
    dd=sp.expand(sum(sp.diff(h[i,j],x[i],x[j]) for i in range(4) for j in range(4)))
    angular=sp.Rational(2,3)*r2*lap_sphere(lap_sphere(chi)+3*chi)
    checks.append(sp.expand(dd-angular)==0)
    angular_basis.append(sphere_reduce(dd)/(2*O0**4))
print('angular normalization',checks, 'seconds',time.monotonic()-t0,flush=True)
source_path=ROOT/'basis/results/sources_cc.pkl'
with source_path.open('rb') as generated:
    source=pickle.load(generated)
if source.get('first_order_ok') is not True:
    raise RuntimeError('Regenerated source fails first-order constraint sanity check')
data=json.loads((ROOT/'basis/results/construct_cc_H.json').read_text())
c={k:sp.sympify(v) for k,v in data['nonzero_coefficients'].items()}
coefficient_checks=[sp.expand(c['c4']-c['c1'])==0,
                    sp.expand(c['c5']+2*c['c2'])==0,
                    sp.expand(c['c7']-c['c2'])==0]
f0=sp.sympify(data['f0'])
numerator,denominator=sp.fraction(source['SH'])
if any(z in denominator.free_symbols for z in x):
    raise RuntimeError('Source denominator depends on spatial coordinates; angular reduction is invalid')
source_sphere=sphere_reduce(numerator)/denominator
print('source angular reduction complete',time.monotonic()-t0,flush=True)
DH=c['c1']*angular_basis[0]+c['c2']*angular_basis[1]
residual_numerator=sp.expand(sp.numer(sp.together(DH-source_sphere+f0)))
identity=residual_numerator==0
wrong_numerator=sp.expand(sp.numer(sp.together(-c['c1']*angular_basis[0]+c['c2']*angular_basis[1]-source_sphere+f0)))
result={'method':'Exact symbolic angular-polynomial reduction modulo |x|^2=s; independent of original operator code',
        'normalization_basis_checks':checks,'coefficient_reconstruction_checks':coefficient_checks,
        'hamiltonian_identity_exact':identity,'wrong_sign_C1_control_detected':wrong_numerator!=0,
        'source_first_order_ok':source['first_order_ok'] is True,
        'source_sha256':hashlib.sha256(source_path.read_bytes()).hexdigest(),
        'coefficient_input_sha256':hashlib.sha256((ROOT/'basis/results/construct_cc_H.json').read_bytes()).hexdigest(),
        'python_optimized':not __debug__,'python':sys.version.split()[0],'sympy':sp.__version__,
        'seconds':round(time.monotonic()-t0,3)}
(HERE/'angular_exact.json').write_text(json.dumps(result,indent=2))
print(json.dumps(result,indent=2),flush=True)
if not (all(checks) and all(coefficient_checks) and identity and result['wrong_sign_C1_control_detected']):
    raise RuntimeError('Exact angular Hamiltonian verification failed; inspect angular_exact.json')
