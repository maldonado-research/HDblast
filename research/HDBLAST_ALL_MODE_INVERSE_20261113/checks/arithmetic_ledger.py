def canonical(value):return (json.dumps(value,sort_keys=True,indent=2)+"\n").encode()


def evaluate(claims,check):
    records=[]
    def need(name,ok):
        boolean=bool(ok);check("arithmetic/"+name,boolean)
        records.append({"name":name,"status":"pass" if boolean else "fail"})
        if not boolean:raise ValueError("arithmetic rejects "+name)
    need("schema",claims["schema"]=="hdblast-all-mode-ledger-claims-v1")
    need("review_status",claims["review_status"]=="accepted_conditional_analytic_inputs")
    ell=F(1,10**6);kappa=ell/100;rho_min=129;rho_max=131
    amin=F(111,1000);amax=F(112,1000);pmax=F(14,100000)
    # Scalar all-mode coercivity: radical estimates are squared with positive
    # sides, so every comparison is an exact rational inequality.
    need("scalar_angular_n_6650",6*rho_max**4/F(40)<6650**2)
    need("scalar_angular_lambda_n_53200",6*rho_max**4*F(8,5)<53200**2)
    need("scalar_Rt_bound",F(3,rho_min**2)+pmax*pmax/3+3*amax*amax<F(4,100))
    need("scalar_tail_k_inverse_squared",rho_max**2*ell*ell/3<F(6,10**9))
    Cn=F(2*53200,3*rho_min**2)+F(4,100)*6650
    need("scalar_C_lambda_n_270",Cn<270)
    need("scalar_tail_forcing",(2+270)*F(6,10**9)<F(2,10**6))
    ny=amax*6650+F(53200,1)/(3*amin*rho_min**2)+F(2,1)/(3*amin)
    need("scalar_radial_ny_800",ny<800)
    need("scalar_transition_nt",F(473,10**8)*800<F(4,1000))
    need("scalar_transition_r4_conversion",F(4,1000)*625==F(5,2))
    need("scalar_one_tail_E32",3*(F(2,10**6)+4*F(5,2))<32)
    need("scalar_one_tail_I22",3*F(71,10)<22)
    need("scalar_nonconstant_gap",64+45*625*6650<2*10**8)
    scalar_gap=F(claims["scalar_gap_mantissa"])*10**claims["scalar_gap_ten_exponent"]
    need("scalar_full_gap",scalar_gap==F(13,10)*10**24*kappa**-4)
    scalar_squared=scalar_gap*scalar_gap
    need("scalar_squared_gap",scalar_squared<10**claims["scalar_inverse_L2_ten_ceiling"])
    # Momentum poloidal and both coexact families. The spectral reductions
    # lambda>=8, mu>=9 are analytic inputs, not generated by this ledger.
    need("momentum_sqrt_three_fifths",F(3,5)<F(4,5)**2)
    need("momentum_inverse_sqrt12",F(1,12)<F(3,10)**2)
    u=F(1000,111)*(F(3,10)+F(4,15))
    need("momentum_u_rational_6",u==F(1700,333) and u<6)
    need("momentum_poloidal_v_36",F(rho_max**2,4)*F(3,2*(8-3))<36**2)
    need("momentum_poloidal_X_37",36**2+6**2<37**2)
    need("momentum_coexact_v_42",F(rho_max**2,2*(9-4))<42**2)
    # Uniform coexact bound decreases with mu>=9 because denominator mu-4
    # increases; the frozen endpoint proof never imposes an upper mode cutoff.
    need("momentum_coexact_spectral_gap",9-4==5)
    need("momentum_bilinear_derivative_three_halves",(F(1,2)+F(4,5))**2+F(1,2)<F(3,2)**2)
    tail=378+F(100001,100000)*(756+F(3,20000))
    need("momentum_tail_C0_1200",tail<F(claims["momentum_gap_kappa_multiplier"]))
    C0=F(claims["momentum_gap_kappa_multiplier"])*kappa**-2
    need("momentum_gap_value",C0==12*10**18)
    deltaW=12*kappa*kappa/(ell*rho_min)
    need("momentum_weight_gradient",deltaW<F(1,10**11))
    qmax=kappa*kappa
    korn_square=F(3,2)*deltaW**2+2*qmax*qmax
    need("momentum_Korn_square_rounding",korn_square<F(2,10**11)**2)
    H1_API=1+(1+F(2,10**11))*C0
    need("momentum_H1_API",H1_API<F(claims["momentum_H1_API_ceiling"]))
    momentum_squared=C0*C0
    need("momentum_squared_gap",momentum_squared==F(claims["momentum_inverse_L2_mantissa"])*10**claims["momentum_inverse_L2_ten_exponent"])
    need("momentum_H1_inverse",F(claims["momentum_H1_API_ceiling"])*C0<
         F(claims["momentum_H1_inverse_mantissa"])*10**claims["momentum_H1_inverse_ten_exponent"])
    # Exact combinatorics in the scalar graph induction.
    need("graph_inner_count",max((j+1)*(j+2)//2 for j in range(15))==claims["graph_inner_count"]==120)
    need("graph_target_count",17*18//2==claims["graph_target_count"]==153)
    comm=claims["graph_commutator_ceiling"]
    need("graph_commutator_count",max(2**j+3 for j in range(15))<comm==10**5)
    graph_factor=12*claims["graph_inner_count"]*comm+3*claims["graph_target_count"]
    need("graph_induction_factor",graph_factor<claims["graph_induction_ceiling"]==10**9)
    increment=claims["graph_J_exponent_per_order"]
    need("graph_exponent_induction",10**9*(1+10**increment)<10**(2*increment) and increment==10)
    need("A6_finite_weight",6**6<10**5)
    need("A6R_finite_weight",6**6*10**6<10**11)
    need("scalar_graph_lower_terms",10**11*10**150+F(9,4)<10**162)
    delta_exp=claims["graph_absorption_delta_ten_exponent"]
    need("scalar_graph_absorption",delta_exp==-164 and 162+delta_exp==-2)
    need("scalar_graph_remaining_left",F(3,4)-F(1,100)==F(74,100))
    A8=claims["scalar_graph_A8_exponent"]
    need("scalar_A8_constant_rounding",162-15*delta_exp+2<=A8==2624)
    J16=claims["scalar_graph_J16_exponent"]
    need("scalar_J16_constant_rounding",A8+16*increment<J16==2800)
    # All-mode norm bridge: slot accounting and exact integer constant.
    Cnorm=13*8**16*math.factorial(16)
    need("norm_bridge_integer",Cnorm==int(claims["norm_bridge_integer"]))
    need("norm_bridge_decimal",Cnorm<10**claims["norm_bridge_decimal_ceiling"] and claims["norm_bridge_decimal_ceiling"]==29)
    need("norm_bridge_pair_count",153<13**2)
    need("norm_bridge_forward_stages",all(6*j+2*r+3<=6*(j+1) for j in range(16) for r in (0,1)))
    need("norm_bridge_reverse_stages",all(max(4*n+2,2*n+3)<=4*(n+1) for n in range(16)))
    need("norm_bridge_angular_lower",all(F(3,4)**order*F(1,3)**(order//2)>=F(1,4)**order for order in range(17)))
    need("norm_bridge_radial_jet_factors",all(F(1,10**8)*(5+8*i)<1 for i in range(64)))
    source_bridge=claims["scalar_bridge_exponent"]
    need("scalar_bridge_generous_rounding",source_bridge==1000 and claims["norm_bridge_decimal_ceiling"]<source_bridge)
    physical_graph=J16+2*source_bridge
    final_exp=claims["scalar_final_inverse_exponent"]
    need("scalar_final_ceiling",physical_graph+claims["scalar_inverse_L2_ten_ceiling"]+1<final_exp==5000)
    # Full momentum graph ledger, including all matrix normal-order costs.
    # The coefficient jets and analytic commutator proof are pinned inputs.
    need("momentum_v1_pointwise",4+12+4<=20)
    need("momentum_v2_pointwise",2*(1+1)**2+8+2+2<=20)
    need("momentum_r1_pointwise",2*(2+1+3)<=12)
    need("momentum_base_cross_absorption",2*F(8*6,10**5)**2<F(1,1000)**2)
    need("momentum_base_quadratic_margin",4-F(2,1000)>=1 and F(2,1000)<=1)
    need("momentum_Young_coefficient",12**2==144)
    base=claims["momentum_base_factor"]
    need("momentum_base_factor",base==256 and F(4,3)<=base and 221<=base)
    exponential_sum=sum((F(1,math.factorial(k)) for k in range(15)),F(0))
    need("momentum_Q_basic_bound",exponential_sum<3)
    need("momentum_Q_v1_bound",4*3**2+12*3**2+4*13*3<=300)
    need("momentum_Q_v2_bound",2*(3+3)**2+8*3**2+2*13*3+2*13*3<=300)
    need("momentum_Q_offdiagonal_bound",2*(3+3*3)+2*(6+3+3*3)<=60)
    Lbudget=claims["momentum_L_coefficient_ceiling"]
    need("momentum_L_coefficient_budget",300+300+60+10<1000<Lbudget==10**4)
    Dstep=claims["momentum_D_step_factor"]
    need("momentum_D_step",15+16*6+1==112<Dstep==130)
    Astep=claims["momentum_A_step_factor"]
    need("momentum_A_step",1+Dstep**2+1==16902<Astep==20000)
    need("momentum_A6_source_budget",Astep**6<10**claims["momentum_A6_source_exponent"] and claims["momentum_A6_source_exponent"]==26)
    need("momentum_A6L_budget",Lbudget*Astep**6<10**claims["momentum_A6L_exponent"] and claims["momentum_A6L_exponent"]==30)
    LA6=Lbudget*Dstep**2*10**claims["momentum_A6_source_exponent"]
    need("momentum_LA6_budget",LA6<10**claims["momentum_LA6_exponent"] and claims["momentum_LA6_exponent"]==35)
    commexp=claims["momentum_commutator_exponent"]
    need("momentum_commutator_budget",Lbudget*Astep**6+LA6<10**commexp and commexp==40)
    need("momentum_commutator_order",2+12-1==claims["momentum_commutator_order"]==13)
    Kexp=claims["momentum_graph_K_exponent"]
    need("momentum_graph_source_rounding",base*10**26<10**29)
    need("momentum_graph_K_rounding",base*(10**(commexp+13*increment)+1)<10**Kexp and Kexp==174)
    need("momentum_spectral_absorption_half",F(1,2)==F(10**Kexp,2*10**Kexp))
    need("momentum_K14_rounding",14*Kexp==2436 and 2**14<10**5)
    A7=claims["momentum_A7_exponent"]
    need("momentum_A7_rounding",14*Kexp+5<A7==2442)
    momentumJ=claims["momentum_J14_exponent"]
    need("momentum_J14_rounding",A7+14*increment==momentumJ==2582)
    need("momentum_norm_source_low_gap_rounding",10**29+F(36,25)*10**38<10**39)
    physical_momentum=claims["momentum_physical_W14_exponent"]
    need("momentum_physical_H14_rounding",momentumJ+29+39==physical_momentum==2650)
    momentum_final=claims["momentum_final_inverse_exponent"]
    need("momentum_final_inverse_rounding",physical_momentum<momentum_final==2700)
    need("combined_Hilbert_inverse",claims["combined_Hilbert_inverse_exponent"]==max(final_exp,momentum_final)==5000)
    return {"schema":"hdblast-all-mode-arithmetic-v1","status":"pass",
        "review_status":claims["review_status"],"claims_sha256":hashlib.sha256(canonical(claims)).hexdigest(),
        "arithmetic":"standard-library Fraction and exact integer powers; no numerical exp evaluation",
        "checks":records,"exact":{
            "scalar_gap":str(scalar_gap),"scalar_squared_gap":str(scalar_squared),
            "momentum_gap":str(C0),"momentum_squared_gap":str(momentum_squared),
            "momentum_H1_API_upper":str(H1_API),"momentum_weight_gradient_upper":str(deltaW),
            "momentum_Korn_square_upper":str(korn_square),"momentum_tail_multiplier":str(tail),
            "graph_induction_multiplier":graph_factor,"norm_bridge_integer":str(Cnorm),
            "momentum_D_step_cost":112,"momentum_A_step_cost":16902,
            "momentum_A6_coefficient_budget":Astep**6,
            "scalar_inverse_ten_exponent":final_exp,"momentum_inverse_ten_exponent":momentum_final,
            "combined_Hilbert_inverse_ten_exponent":claims["combined_Hilbert_inverse_exponent"]},
        "scope":"Exact arithmetic conditional on accepted, separately pinned all-mode coercivity, scalar/vector graph, domain and norm-bridge proofs. No nonlinear parameter radius or evolved tube follows."}


def controls(claims):
    records=[]
    mutations=(("scalar_gap_mantissa","13/100"),("scalar_inverse_L2_ten_ceiling",112),
        ("momentum_inverse_L2_mantissa","18/25"),("momentum_H1_API_ceiling","10000000000000000000"),
        ("graph_induction_ceiling",100000000),("graph_absorption_delta_ten_exponent",-161),
        ("norm_bridge_integer","7656014335380773516240486400"),
        ("momentum_D_step_factor",100),("momentum_A_step_factor",16000),
        ("momentum_graph_K_exponent",170),("momentum_A7_exponent",2436),
        ("momentum_physical_W14_exponent",2649),("combined_Hilbert_inverse_exponent",2700))
    for name,value in mutations:
        bad=copy.deepcopy(claims);bad[name]=value;encoded=canonical(bad)
        try:evaluate(json.loads(encoded),lambda name,ok:None)
        except ValueError as exc:records.append({"fault":name,"self_rehashed_sha256":hashlib.sha256(encoded).hexdigest(),
            "rejected_by":"fresh exact rational or combinatorial arithmetic oracle","diagnostic":str(exc)})
        else:raise ValueError("surviving ledger fault: "+name)
    return {"schema":"hdblast-all-mode-arithmetic-controls-v1","status":"pass","controls":records}


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--claims",type=Path,default=Path(__file__).with_name("ledger_claims.json"))
    parser.add_argument("--report",type=Path);parser.add_argument("--controls",type=Path)
    args=parser.parse_args(argv)
    try:
        claims=json.loads(args.claims.read_text());report=evaluate(claims,lambda name,ok:None)
        encoded=canonical(report)
        if args.report:args.report.write_bytes(encoded)
        if args.controls:args.controls.write_bytes(canonical(controls(claims)))
        sys.stdout.buffer.write(encoded);return 0
    except (ValueError,KeyError,TypeError,OSError) as exc:sys.stderr.write(str(exc)+"\n");return 1


if __name__=="__main__":raise SystemExit(main())
