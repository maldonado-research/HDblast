#!/usr/bin/env python3
"""Exact all-mode arithmetic conditional on the accepted analytic proofs.

Arithmetic and finite coefficient accounting are checked here. The analytic
coercivity, graph, domain and norm-bridge proofs are separate pinned inputs.
"""
from __future__ import annotations
import argparse
import copy
